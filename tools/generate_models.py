#!/usr/bin/env python3
"""
generate_models.py -- regenerates the bundled OBJ assets for the M3 sandbox.

All models are emitted with:
  - `v` positions and `vn` normals
  - triangulated `f` faces in `v//vn` form
  - no material files: PBR materials are assigned per model in sandbox/main.cpp

Deterministic output (parametric math, fixed seeds) so regenerated assets are
reproducible. Usage:

    python3 tools/generate_models.py [output_dir]

Default output_dir: sandbox/assets/models (relative to the project root).
"""

import math
import os
import sys

MODELS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "..", "sandbox", "assets", "models")


# ---------------------------------------------------------------------------
# OBJ emission
# ---------------------------------------------------------------------------

class ObjBuilder:
    """Accumulates triangles, deduplicates (position, normal) corners, and
    writes a Wavefront OBJ with `v//vn` faces."""

    def __init__(self):
        self.positions = []          # (x, y, z)
        self.normals = []            # (x, y, z)
        self.triangles = []          # ((vi, ni), (vi, ni), (vi, ni))
        self._cache = {}             # (pos, nrm) -> 0-based corner id

    def _corner(self, position, normal):
        key = (position, normal)
        if key not in self._cache:
            self._cache[key] = (len(self.positions), len(self.normals))
            self.positions.append(position)
            self.normals.append(normal)
        return self._cache[key]

    def add_triangle(self, a, b, c, na, nb, nc):
        # Safety net: never emit zero-area triangles (UV poles, repeated
        # corners). Mirrors the degeneracy rejection the C++ loader applies.
        ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
        vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
        crx, cry, crz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        if crx * crx + cry * cry + crz * crz < 1e-16:
            return
        pa = self._corner(a, na)
        pb = self._corner(b, nb)
        pc = self._corner(c, nc)
        self.triangles.append((pa, pb, pc))

    def add_outward_triangle(self, a, b, c, na, nb, nc):
        """Adds a triangle, flipping the winding if needed so the geometric
        face normal agrees with the supplied vertex normals. Winding bugs are
        impossible to see in a text editor -- this makes them impossible to
        ship, too."""
        g = _fnorm(a, b, c)
        avg = (na[0] + nb[0] + nc[0], na[1] + nb[1] + nc[1], na[2] + nb[2] + nc[2])
        if g[0] * avg[0] + g[1] * avg[1] + g[2] * avg[2] < 0.0:
            b, c = c, b
            nb, nc = nc, nb
        self.add_triangle(a, b, c, na, nb, nc)

    def add_outward_flat_quad(self, a, b, c, d):
        """Adds a two-sided flat quad (for zero-thickness fins): both windings,
        same face normal."""
        n = _fnorm(a, b, c)
        self.add_triangle(a, b, c, n, n, n)
        self.add_triangle(a, c, d, n, n, n)
        self.add_triangle(d, c, b, n, n, n)
        self.add_triangle(d, b, a, n, n, n)

    def vertex_count(self):
        return len(self.positions)

    def triangle_count(self):
        return len(self.triangles)

    def write(self, path):
        with open(path, "w") as f:
            f.write("# Generated by tools/generate_models.py -- do not edit by hand.\n")
            f.write("# Deterministic output; regenerate with: python3 tools/generate_models.py\n")
            for p in self.positions:
                f.write("v %.6f %.6f %.6f\n" % p)
            for n in self.normals:
                f.write("vn %.6f %.6f %.6f\n" % n)
            for (a, b, c) in self.triangles:
                f.write("f %d//%d %d//%d %d//%d\n" % (
                    a[0] + 1, a[1] + 1,
                    b[0] + 1, b[1] + 1,
                    c[0] + 1, c[1] + 1))


def _fnorm(a, b, c):
    """Geometric normal from three vertices in winding order."""
    ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
    vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
    nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
    l = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
    return (nx / l, ny / l, nz / l)


# ---------------------------------------------------------------------------
# Model: UV torus (smooth normals) -- metallic specular showcase
# ---------------------------------------------------------------------------

def build_torus(builder, R=0.72, r=0.30, seg_u=48, seg_v=24):
    def point(u, v):
        cu, su = math.cos(u), math.sin(u)
        cv, sv = math.cos(v), math.sin(v)
        return ((R + r * cv) * cu, r * sv, (R + r * cv) * su)

    def normal(u, v):
        cu, su = math.cos(u), math.sin(u)
        cv, sv = math.cos(v), math.sin(v)
        return (cv * cu, sv, cv * su)

    for i in range(seg_u):
        u0 = 2 * math.pi * i / seg_u
        u1 = 2 * math.pi * (i + 1) / seg_u
        for j in range(seg_v):
            v0 = 2 * math.pi * j / seg_v
            v1 = 2 * math.pi * (j + 1) / seg_v

            p00, p10, p01, p11 = point(u0, v0), point(u1, v0), point(u0, v1), point(u1, v1)
            n00, n10 = normal(u0, v0), normal(u1, v0)
            n01, n11 = normal(u0, v1), normal(u1, v1)

            builder.add_outward_triangle(p00, p10, p11, n00, n10, n11)
            builder.add_outward_triangle(p00, p11, p01, n00, n11, n01)


# ---------------------------------------------------------------------------
# Model: UV sphere (smooth normals) -- the classic specular-highlight test
# ---------------------------------------------------------------------------

def build_sphere(builder, radius=0.6, slices=48, stacks=32):
    def point(s, p):
        phi = math.pi * s / stacks
        theta = 2 * math.pi * p / slices
        n = (math.sin(phi) * math.cos(theta), math.cos(phi),
             math.sin(phi) * math.sin(theta))
        return (radius * n[0], radius * n[1], radius * n[2]), n

    for s in range(stacks):
        for p in range(slices):
            p00, n00 = point(s, p)
            p10, n10 = point(s, p + 1)
            p01, n01 = point(s + 1, p)
            p11, n11 = point(s + 1, p + 1)
            # At the poles the quad collapses: p00==p10 (s=0) or p01==p11
            # (s=stacks-1). ObjBuilder drops the zero-area triangle.
            builder.add_outward_triangle(p00, p01, p11, n00, n01, n11)
            builder.add_outward_triangle(p00, p11, p10, n00, n11, n10)


